const assert = require('node:assert/strict');
const C = require('./engine.js');
const seed = C.createSeed();
assert.equal(seed.orders.length,30);
assert.equal(seed.parcels.length,34);
assert.equal(C.byMerchant(seed,'m1').length,12);
assert.equal(C.byMerchant(seed,'m2').length,10);
assert.equal(C.byMerchant(seed,'m3').length,8);
const student = C.addStudentOrder(seed,'m1',{'p11':1},C.points[0]);
assert.equal(C.orderStatus(seed,seed.orders.find(o=>o.id===student)),'待商家接单');
C.cutoff(seed);
assert.throws(()=>C.addStudentOrder(seed,'m1',{'p11':1},C.points[0]),/截单/);
for(const m of seed.merchants){C.acceptMerchant(seed,m.id);C.packMerchant(seed,m.id);}
assert.throws(()=>C.pickupMerchant(seed,'m3',false),/上一站/);
for(const m of seed.merchants)C.pickupMerchant(seed,m.id,false);
assert.equal(C.totals(seed).picked,35);
C.depart(seed);
C.campusReceive(seed);
C.assignDelivery(seed);
C.completeDelivery(seed);
assert.equal(seed.batch.status,'finished');
assert.equal(C.totals(seed).delivered,35);
const short = C.createSeed();C.cutoff(short);
for(const m of short.merchants){C.acceptMerchant(short,m.id);C.packMerchant(short,m.id);}
C.pickupMerchant(short,'m1',false);
C.pickupMerchant(short,'m2',false);
C.pickupMerchant(short,'m3',true);
assert.equal(C.totals(short).missing,1);
assert.equal(short.issues.length,1);
const missingOrder=short.orders.find(o=>o.id===short.issues[0].orderId);
assert.equal(C.orderStatus(short,missingOrder),'取货异常');
C.depart(short);
assert.equal(C.orderStatus(short,missingOrder),'取货异常');
C.campusReceive(short);C.assignDelivery(short);C.completeDelivery(short);
assert.equal(short.batch.status,'delivering');
C.resolveIssue(short,short.issues[0].id);
assert.equal(short.batch.status,'finished');
assert.equal(short.issues[0].status,'resolved');
assert.equal(C.orderStatus(short,missingOrder),'已模拟退款');
assert.equal(C.totals(short).refunded,1);
assert.throws(()=>C.resolveIssue(short,short.issues[0].id),/已经处理/);
C.changeFixedCost(short,110);
assert.equal(short.costs.fixed,110);
assert.ok(Number.isFinite(C.totals(short).contribution));
console.log('PASS: seed 30 orders / 34 parcels; student ordering, cutoff, merchant packing, route order, full delivery, shortage exception, refund, cost.');
